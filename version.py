def parse(v):
    """'v1.4.0' → (1, 4, 0) для сравнения версий."""
    v = str(v or "").strip().lstrip("vV")
    out = []
    for part in v.split("."):
        num = "".join(ch for ch in part if ch.isdigit())
        out.append(int(num) if num else 0)
    return tuple((out + [0, 0, 0])[:3])
